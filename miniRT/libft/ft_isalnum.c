int	ft_isalnum(int c)
{
	if ((c >= (int) 'a' && c <= (int) 'z')
		|| (c >= (int) 'A' && c <= (int) 'Z')
		|| (c >= (int) '0' && c <= (int) '9'))
		return (8);
	else
		return (0);
}
